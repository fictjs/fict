import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = join(root, 'packages/compiler/compiler-capabilities.json')
const packagePath = join(root, 'packages/compiler/package.json')
const typescriptPath = join(root, 'packages/compiler/src/compiler-capabilities.generated.ts')
const rustPath = join(root, 'crates/fict-compiler/src/capabilities.generated.rs')
const check = process.argv.includes('--check')

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
const compilerPackage = JSON.parse(await readFile(packagePath, 'utf8'))
validateManifest(manifest, compilerPackage.version)

const digest = `sha256:${createHash('sha256').update(JSON.stringify(manifest)).digest('hex')}`
const rawTypescript = `// @generated by scripts/generate-compiler-capabilities.mjs; do not edit.\n\nexport const COMPILER_CAPABILITY_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const\nexport const COMPILER_CAPABILITY_MANIFEST_DIGEST = ${JSON.stringify(digest)}\n`
const typescript = await format(rawTypescript, {
  ...(await resolveConfig(typescriptPath)),
  filepath: typescriptPath,
})
const rust = `// @generated by scripts/generate-compiler-capabilities.mjs; do not edit.\n\n/// Compiler capability manifest schema version.\npub const COMPILER_CAPABILITY_MANIFEST_VERSION: u32 = ${manifest.schemaVersion};\n/// Package version whose behavior the capability manifest describes.\npub const COMPILER_CAPABILITY_PACKAGE_VERSION: &str = ${JSON.stringify(manifest.packageVersion)};\n/// SHA-256 of the canonical compiler capability manifest.\npub const COMPILER_CAPABILITY_MANIFEST_DIGEST: &str = ${JSON.stringify(digest)};\n`

if (check) {
  await Promise.all([assertCurrent(typescriptPath, typescript), assertCurrent(rustPath, rust)])
} else {
  await Promise.all([writeFile(typescriptPath, typescript), writeFile(rustPath, rust)])
}

function validateManifest(value, packageVersion) {
  const expectedOptions = {
    dev: { default: false, supported: [false, true] },
    lazyConditional: { default: true, supported: [false, true] },
    getterCache: { default: true, supported: [false, true] },
    optimizeLevel: { default: 'safe', supported: ['safe', 'full'] },
    inlineDerivedMemos: { default: true, supported: [false, true] },
  }
  if (
    typeof value !== 'object' ||
    value === null ||
    Array.isArray(value) ||
    Object.keys(value).sort().join(',') !== 'backend,options,packageVersion,schemaVersion'
  ) {
    throw new Error('compiler capability manifest has an unknown top-level shape')
  }
  if (value.schemaVersion !== 1 || value.backend !== 'rust') {
    throw new Error('compiler capability manifest must describe Rust schema v1')
  }
  if (value.packageVersion !== packageVersion) {
    throw new Error(
      `compiler capability packageVersion ${String(value.packageVersion)} does not match ${packageVersion}`,
    )
  }
  if (JSON.stringify(value.options) !== JSON.stringify(expectedOptions)) {
    throw new Error('compiler capability option support does not match the reviewed native matrix')
  }
}

async function assertCurrent(path, expected) {
  const actual = await readFile(path, 'utf8').catch(() => '')
  if (actual !== expected) {
    throw new Error(`${path} is stale; run pnpm generate:compiler-capabilities`)
  }
}
