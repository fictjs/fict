import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = join(root, 'packages/compiler/metadata-protocol.json')
const typescriptPath = join(root, 'packages/compiler/src/metadata-protocol.generated.ts')
const rustPath = join(root, 'crates/fict-metadata/src/metadata_protocol.generated.rs')
const check = process.argv.includes('--check')

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
validateManifest(manifest)

const typescript = `// @generated by scripts/generate-metadata-protocol.mjs; do not edit.\n\n/** Current module-reactivity metadata schema version. */\nexport const MODULE_REACTIVE_METADATA_VERSION = ${manifest.schemaVersion}\n/** Maximum recursive namespace depth accepted from a metadata snapshot. */\nexport const MAX_METADATA_NAMESPACE_DEPTH = ${manifest.maxNamespaceDepth}\n`
const rust = `// @generated by scripts/generate-metadata-protocol.mjs; do not edit.\n\n/// Current module-reactivity metadata schema version.\npub const MODULE_REACTIVE_METADATA_VERSION: u32 = ${manifest.schemaVersion};\n/// Maximum recursive namespace depth accepted from a metadata snapshot.\npub const MAX_METADATA_NAMESPACE_DEPTH: usize = ${manifest.maxNamespaceDepth};\n`

if (check) {
  await Promise.all([assertCurrent(typescriptPath, typescript), assertCurrent(rustPath, rust)])
} else {
  await Promise.all([writeFile(typescriptPath, typescript), writeFile(rustPath, rust)])
}

function validateManifest(value) {
  if (
    typeof value !== 'object' ||
    value === null ||
    Array.isArray(value) ||
    Object.keys(value).sort().join(',') !== 'maxNamespaceDepth,schemaVersion'
  ) {
    throw new Error('metadata protocol must define only schemaVersion and maxNamespaceDepth')
  }
  if (!Number.isInteger(value.schemaVersion) || value.schemaVersion < 1) {
    throw new Error('metadata schemaVersion must be a positive integer')
  }
  if (!Number.isInteger(value.maxNamespaceDepth) || value.maxNamespaceDepth < 1) {
    throw new Error('metadata maxNamespaceDepth must be a positive integer')
  }
}

async function assertCurrent(path, expected) {
  const actual = await readFile(path, 'utf8').catch(() => '')
  if (actual !== expected) throw new Error(`${path} is stale; run pnpm generate:metadata-protocol`)
}
