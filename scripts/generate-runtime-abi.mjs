import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = join(root, 'packages/runtime/runtime-abi.json')
const tsPath = join(root, 'packages/compiler/src/runtime-abi.generated.ts')
const rustPath = join(root, 'crates/fict-emit/src/runtime_abi.generated.rs')
const check = process.argv.includes('--check')
const bootstrap = process.argv.includes('--bootstrap')
const previewHelpers = new Set([
  'useLexicalScope',
  'getScopeProps',
  'setComponentMeta',
  'getComponentMeta',
  'qrl',
  'getSSRScope',
  'ensureScope',
  'prepareContext',
  'enterHydration',
  'exitHydration',
  'domRender',
  'hydrateComponent',
  'registerResume',
])

if (bootstrap) {
  const constants = await readFile(join(root, 'packages/compiler/src/constants.ts'), 'utf8')
  const body = constants.match(/export const RUNTIME_HELPERS = \{([\s\S]*?)\n\} as const/)?.[1]
  if (!body) throw new Error('could not bootstrap RUNTIME_HELPERS from constants.ts')
  const helpers = [...body.matchAll(/^\s*(\w+):\s*'([^']+)',?$/gm)].map(match => ({
    key: match[1],
    export: match[2],
    preferredLocal: match[2],
    module: match[1] === 'keyedList' ? 'list' : 'internal',
    stability: previewHelpers.has(match[1]) ? 'preview' : 'core',
  }))
  await writeFile(
    manifestPath,
    `${JSON.stringify(
      {
        version: 1,
        families: {
          fict: { internal: 'fict/internal', list: 'fict/internal/list' },
          runtime: {
            internal: '@fictjs/runtime/internal',
            list: '@fictjs/runtime/internal/list',
          },
        },
        helpers,
      },
      null,
      2,
    )}\n`,
  )
}

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
validateManifest(manifest)
const ts = generateTypeScript(manifest)
const rust = generateRust(manifest)

if (check) {
  await assertCurrent(tsPath, ts)
  await assertCurrent(rustPath, rust)
} else {
  await writeFile(tsPath, ts)
  await writeFile(rustPath, rust)
}

function validateManifest(manifest) {
  if (!Number.isInteger(manifest.version) || manifest.version < 1) {
    throw new Error('runtime ABI version must be a positive integer')
  }
  const keys = new Set()
  for (const helper of manifest.helpers ?? []) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(helper.key))
      throw new Error(`invalid helper key: ${helper.key}`)
    if (!/^[$A-Z_a-z][$\w]*$/.test(helper.export)) {
      throw new Error(`invalid helper export: ${helper.export}`)
    }
    if (keys.has(helper.key)) throw new Error(`duplicate helper key: ${helper.key}`)
    keys.add(helper.key)
    if (!['internal', 'list'].includes(helper.module)) {
      throw new Error(`invalid helper module: ${helper.key}`)
    }
    if (!['core', 'preview'].includes(helper.stability)) {
      throw new Error(`invalid helper stability: ${helper.key}`)
    }
  }
}

function generateTypeScript(manifest) {
  const object = field =>
    manifest.helpers.map(helper => `  ${helper.key}: ${JSON.stringify(helper[field])},`).join('\n')
  return `// @generated by scripts/generate-runtime-abi.mjs; do not edit.\n\nexport const RUNTIME_ABI_VERSION = ${manifest.version} as const\n\nexport const RUNTIME_MODULES = ${JSON.stringify(manifest.families, null, 2)} as const\n\nexport const RUNTIME_HELPERS = {\n${object('export')}\n} as const\n\nexport const RUNTIME_ALIASES = {\n${object('preferredLocal')}\n} as const\n\nexport const RUNTIME_HELPER_MODULES = {\n${object('module')}\n} as const\n\nexport const RUNTIME_HELPER_STABILITY = {\n${object('stability')}\n} as const\n`
}

function generateRust(manifest) {
  const variants = manifest.helpers.map(helper => `    ${pascal(helper.key)},`).join('\n')
  const all = manifest.helpers.map(helper => `    RuntimeHelper::${pascal(helper.key)},`).join('\n')
  const specs = manifest.helpers
    .map(
      helper =>
        `    RuntimeHelperSpec {\n        helper: RuntimeHelper::${pascal(helper.key)},\n        key: ${JSON.stringify(helper.key)},\n        export: ${JSON.stringify(helper.export)},\n        preferred_local: ${JSON.stringify(helper.preferredLocal)},\n        module: RuntimeHelperModule::${pascal(helper.module)},\n        stability: RuntimeHelperStability::${pascal(helper.stability)},\n    },`,
    )
    .join('\n')
  return `// @generated by scripts/generate-runtime-abi.mjs; do not edit.\n\npub const RUNTIME_ABI_VERSION: u32 = ${manifest.version};\npub const FICT_INTERNAL_MODULE: &str = ${JSON.stringify(manifest.families.fict.internal)};\npub const FICT_LIST_MODULE: &str = ${JSON.stringify(manifest.families.fict.list)};\npub const STANDALONE_INTERNAL_MODULE: &str = ${JSON.stringify(manifest.families.runtime.internal)};\npub const STANDALONE_LIST_MODULE: &str = ${JSON.stringify(manifest.families.runtime.list)};\n\n#[repr(u16)]\n#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\npub enum RuntimeHelper {\n${variants}\n}\n\npub const ALL_RUNTIME_HELPERS: &[RuntimeHelper] = &[\n${all}\n];\n\npub const RUNTIME_HELPER_SPECS: &[RuntimeHelperSpec] = &[\n${specs}\n];\n`
}

function pascal(value) {
  return value.replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, _prefix, char) => char.toUpperCase())
}

async function assertCurrent(path, expected) {
  const actual = await readFile(path, 'utf8').catch(() => '')
  if (actual !== expected) throw new Error(`${path} is stale; run pnpm generate:runtime-abi`)
}
